"""OpenRAM macro generation for py2hwsw ASIC flow."""

import hashlib
import json
import os
import subprocess
import sys


def get_recipe_key(recipe):
    m = hashlib.sha256()
    m.update(json.dumps(recipe, sort_keys=True).encode())
    return m.hexdigest()[:16]


def ensure_dir(path):
    os.makedirs(path, exist_ok=True)
    return path


def get_openram_env():
    env = os.environ.copy()
    # Try to find OpenRAM installation
    if not env.get("OPENRAM_HOME"):
        # Check common nix store paths
        for root in ["/nix/store", os.environ.get("HOME", "")]:
            pass
    return env


def generate_macro(recipe, out_dir):
    """Generate a single OpenRAM macro from recipe."""
    macro_name = recipe["name"]
    macro_dir = os.path.join(out_dir, macro_name)
    ensure_dir(macro_dir)
    
    # Check if already generated
    if os.path.exists(os.path.join(macro_dir, f"{macro_name}.lef")) and \
       os.path.exists(os.path.join(macro_dir, f"{macro_name}.gds")):
        return macro_dir
    
    # Write config file for OpenRAM
    config_path = os.path.join(macro_dir, f"{macro_name}.py")
    with open(config_path, "w") as f:
        f.write("# OpenRAM config generated by py2hwsw\n")
        if recipe["type"] == "sram":
            f.write(f'output_name = "{macro_name}"\n')
            f.write(f'output_path = "{macro_dir}"\n')
            f.write(f'num_words = {recipe["num_words"]}\n')
            f.write(f'word_size = {recipe["word_size"]}\n')
            f.write(f'write_size = {recipe.get("write_size", recipe["word_size"])}\n')
            f.write(f'num_rw_ports = {recipe.get("num_rw_ports", 1)}\n')
            f.write(f'num_r_ports = {recipe.get("num_r_ports", 1)}\n')
            f.write(f'num_w_ports = {recipe.get("num_w_ports", 0)}\n')
            f.write(f'tech_name = "{recipe.get("tech_name", "sky130")}"\n')
            f.write(f'nominal_corner_only = {recipe.get("nominal_corner_only", True)}\n')
            f.write(f'unify = {recipe.get("uniquify", True)}\n')
        elif recipe["type"] == "rom":
            f.write(f'output_name = "{macro_name}"\n')
            f.write(f'output_path = "{macro_dir}"\n')
            f.write(f'word_size = {recipe["word_size"]}\n')
            f.write(f'rom_data = "{recipe["rom_data"]}"\n')
            f.write(f'data_type = "{recipe.get("data_type", "hex")}"\n')
            f.write(f'tech_name = "{recipe.get("tech_name", "sky130")}"\n')
            f.write(f'nominal_corner_only = {recipe.get("nominal_corner_only", True)}\n')
    
    # Run OpenRAM compiler
    env = get_openram_env()
    try:
        if recipe["type"] == "sram":
            cmd = [sys.executable, "-m", "openram.sram_compiler", config_path]
        elif recipe["type"] == "rom":
            cmd = [sys.executable, "-m", "openram.rom_compiler", config_path]
        else:
            raise ValueError(f"Unknown recipe type {recipe['type']}")
        
        result = subprocess.run(cmd, cwd=macro_dir, env=env, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        if result.returncode != 0:
            print(result.stdout.decode())
            print(result.stderr.decode(), file=sys.stderr)
            raise RuntimeError(f"OpenRAM generation failed for {macro_name}")
    except Exception as e:
        print(f"Error generating {macro_name}: {e}", file=sys.stderr)
        raise
    
    return macro_dir


def collect_macros(recipes, out_dir):
    """Generate all macros and return MACROS dict for LibreLane."""
    macros = {}
    for recipe in recipes:
        macro_dir = generate_macro(recipe, out_dir)
        macro_name = recipe["name"]
        views = {"gds": [], "lef": [], "nl": [], "lib": {}}
        
        gds = os.path.join(macro_dir, f"{macro_name}.gds")
        lef = os.path.join(macro_dir, f"{macro_name}.lef")
        vh = os.path.join(macro_dir, f"{macro_name}.v")
        
        if os.path.exists(gds):
            views["gds"] = [gds]
        if os.path.exists(lef):
            views["lef"] = [lef]
        if os.path.exists(vh):
            views["nl"] = [vh]  # Use nl for netlist
        
        # Find liberty files
        import glob
        libs = glob.glob(os.path.join(macro_dir, f"*{macro_name}*.lib"))
        if libs:
            views["lib"] = {"*": libs}
        elif glob.glob(os.path.join(macro_dir, "*.lib")):
            libs = glob.glob(os.path.join(macro_dir, "*.lib"))
            views["lib"] = {"*": libs}
        
        if views["gds"] and views["lef"]:
            macros[macro_name] = views
    
    return macros
