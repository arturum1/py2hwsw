def generate_macro(recipe, out_dir):
    """Generate a single OpenRAM macro from recipe."""
    macro_name = recipe["name"]
    macro_dir = os.path.join(out_dir, macro_name)
    ensure_dir(macro_dir)
    
    # Check if already generated
    if os.path.exists(os.path.join(macro_dir, f"{macro_name}.lef")) and \
       os.path.exists(os.path.join(macro_dir, f"{macro_name}.gds")):
        return macro_dir
    
    # Write config file for OpenRAM
    config_path = os.path.join(macro_dir, f"{macro_name}.py")
    with open(config_path, "w") as f:
        f.write("# OpenRAM config generated by py2hwsw\n")
        if recipe["type"] == "sram":
            f.write(f'output_name = "{macro_name}"\n')
            f.write(f'output_path = "{macro_dir}"\n')
            f.write(f'num_words = {recipe["num_words"]}\n')
            f.write(f'word_size = {recipe["word_size"]}\n')
            f.write(f'write_size = {recipe.get("write_size", recipe["word_size"])}\n')
            f.write(f'num_rw_ports = {recipe.get("num_rw_ports", 1)}\n')
            f.write(f'num_r_ports = {recipe.get("num_r_ports", 1)}\n')
            f.write(f'num_w_ports = {recipe.get("num_w_ports", 0)}\n')
            f.write(f'tech_name = "{recipe.get("tech_name", "sky130")}"\n')
            f.write(f'nominal_corner_only = {recipe.get("nominal_corner_only", True)}\n')
            f.write(f'unify = {recipe.get("uniquify", True)}\n')
        elif recipe["type"] == "rom":
            f.write(f'output_name = "{macro_name}"\n')
            f.write(f'output_path = "{macro_dir}"\n')
            f.write(f'word_size = {recipe["word_size"]}\n')
            f.write(f'rom_data = "{recipe["rom_data"]}"\n')
            f.write(f'data_type = "{recipe.get("data_type", "hex")}"\n')
            f.write(f'tech_name = "{recipe.get("tech_name", "sky130")}"\n')
            f.write(f'nominal_corner_only = {recipe.get("nominal_corner_only", True)}\n')
    
    # Run OpenRAM compiler
    env = get_openram_env()
    try:
        if recipe["type"] == "sram":
            cmd = ["/nix/store/3lll9y925zz9393sa59h653xik66srjb-python3-3.13.9/bin/python3", "/home/artur/openram_work/openram/sram_compiler.py", config_path]
        elif recipe["type"] == "rom":
            cmd = ["/nix/store/3lll9y925zz9393sa59h653xik66srjb-python3-3.13.9/bin/python3", "/home/artur/openram_work/openram/rom_compiler.py", config_path]
        else:
            raise ValueError(f"Unknown recipe type {recipe['type']}")
        
        result = subprocess.run(cmd, cwd=macro_dir, env=env, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        if result.returncode != 0:
            print(result.stdout.decode())
            print(result.stderr.decode(), file=sys.stderr)
            raise RuntimeError(f"OpenRAM generation failed for {macro_name}")
    except Exception as e:
        print(f"Error generating {macro_name}: {e}", file=sys.stderr)
        raise
    
    return macro_dir


def collect_macros(recipes, out_dir):
    """Generate all macros and return MACROS dict for LibreLane."""
    macros = {}
    for recipe in recipes:
        macro_dir = generate_macro(recipe, out_dir)
        macro_name = recipe["name"]
        views = {"gds": [], "lef": [], "nl": [], "lib": {}}
        
        gds = os.path.join(macro_dir, f"{macro_name}.gds")
        lef = os.path.join(macro_dir, f"{macro_name}.lef")
        vh = os.path.join(macro_dir, f"{macro_name}.v")
        
        if os.path.exists(gds):
            views["gds"] = [gds]
        if os.path.exists(lef):
            views["lef"] = [lef]
        if os.path.exists(vh):
            views["nl"] = [vh]  # Use nl for netlist
        
        # Find liberty files
        import glob
        libs = glob.glob(os.path.join(macro_dir, f"*{macro_name}*.lib"))
        if libs:
            views["lib"] = {"*": libs}
        elif glob.glob(os.path.join(macro_dir, "*.lib")):
            libs = glob.glob(os.path.join(macro_dir, "*.lib"))
            views["lib"] = {"*": libs}
        
        if views["gds"] and views["lef"]:
            macros[macro_name] = views
    
    return macros


def convert_rom_hex(hex_path, out_path):
    """Convert $readmemh-style hex file to single continuous hex string."""
    with open(hex_path, "r") as f:
        lines = [line.split("//")[0].strip() for line in f if line.strip() and not line.startswith("//")]
    # Remove @address directives (start with @)
    lines = [line for line in lines if not line.startswith("@")]
    words = []
    for line in lines:
        # Each token may be a hex value; take the first token if multiple per line
        tokens = line.split()
        for tok in tokens:
            words.append(tok)
    # Pad each to 8 hex chars (32 bits = 8 hex chars) then concatenate
    padded = [w.zfill(8) for w in words]
    continuous = "".join(padded)
    with open(out_path, "w") as f:
        f.write(continuous)
    return out_path


def generate_includes(macros, out_dir, recipes):
    """Generate sram_1rw1r_macros.vh and rom_1rw_macros.vh from recipes + macros."""
    # SRAM include: build if-tree from SRAM recipes
    sram_recipes = [r for r in recipes if r.get("type") == "sram"]
    rom_recipes = [r for r in recipes if r.get("type") == "rom"]
    sram_path = os.path.join(out_dir, "sram_1rw1r_macros.vh")
    rom_path = os.path.join(out_dir, "rom_1rw_macros.vh")

    with open(sram_path, "w") as f:
        f.write("// Auto-generated SRAM macro include\n")
        f.write("// Generated by openram_gen.py\n")
        # Generate a chain of if branches for SRAM recipes
        if sram_recipes:
            for idx, r in enumerate(sram_recipes):
                addr_w = r.get("num_words")
                # Derive ADDR_WIDTH from num_words if needed; assume ADDR_WIDTH = log2(num_words)
                # But recipes don't include ADDR_WIDTH directly; compute from num_words
                import math
                addr_w_int = int(math.log2(r.get("num_words", 1))) if r.get("num_words", 1) > 0 else 1
                data_w = r.get("word_size", 32)
                write_size = r.get("write_size", data_w)
                macro_name = r.get("name", "behavioral")
                f.write(f"    if ((ADDR_WIDTH == {addr_w_int}) && (DATA_WIDTH == {data_w}) && (WRITE_SIZE == {write_size})) begin : g_macro_{idx}\n")
                # Use actual module name; include power pins conditionally
                f.write(f"        {macro_name} u_sram (\n")
                f.write("        `ifdef USE_POWER_PINS\n")
                # Extract power pin names from macro .v model header (heuristic: vccd1/vssd1 for sky130)
                # Since the wrapper passes .VPWR/.VGND, and macro uses `ifdef USE_POWER_PINS`, connect both.
                f.write("            .vccd1(VPWR), .vssd1(VGND),\n")
                f.write("        `endif\n")
                f.write("            .clk0(clk), .csb0(csb0), .web0(web0)")
                if write_size != data_w:
                    f.write(", .wmask0(wmask0)")
                f.write(",\n")
                f.write("            .addr0(addr0), .din0(din0), .dout0(dout0),\n")
                f.write("            .clk1(clk), .csb1(csb1), .addr1(addr1), .dout1(dout1)\n")
                f.write("        );\n")
                f.write("    end")
                if idx < len(sram_recipes) - 1:
                    f.write(" else ")
                else:
                    f.write("\n")
            # After all macro branches, add behavioral fallback else
            f.write("    else begin : g_behavioral\n")
            f.write("        sram_1rw1r_behavioral #(\n")
            f.write("            .ADDR_WIDTH (ADDR_WIDTH),\n")
            f.write("            .DATA_WIDTH (DATA_WIDTH)\n")
            f.write("        ) u_sram (\n")
            f.write("            .clk    (clk),\n")
            f.write("            .csb0   (csb0),\n")
            f.write("            .web0   (web0),\n")
            f.write("            .wmask0 (wmask0),\n")
            f.write("            .addr0  (addr0),\n")
            f.write("            .din0   (din0),\n")
            f.write("            .dout0  (dout0),\n")
            f.write("            .csb1   (csb1),\n")
            f.write("            .addr1  (addr1),\n")
            f.write("            .dout1  (dout1)\n")
            f.write("        );\n")
            f.write("    end\n")
        else:
            # No SRAM recipes: pure behavioral
            f.write("begin : g_behavioral\n")
            f.write("    sram_1rw1r_behavioral #(\n")
            f.write("        .ADDR_WIDTH (ADDR_WIDTH),\n")
            f.write("        .DATA_WIDTH (DATA_WIDTH)\n")
            f.write("    ) u_sram (\n")
            f.write("        .clk    (clk),\n")
            f.write("        .csb0   (csb0),\n")
            f.write("        .web0   (web0),\n")
            f.write("        .wmask0 (wmask0),\n")
            f.write("        .addr0  (addr0),\n")
            f.write("        .din0   (din0),\n")
            f.write("        .dout0  (dout0),\n")
            f.write("        .csb1   (csb1),\n")
            f.write("        .addr1  (addr1),\n")
            f.write("        .dout1  (dout1)\n")
            f.write("    );\n")
            f.write("end\n")

    with open(rom_path, "w") as f:
        f.write("// Auto-generated ROM macro include\n")
        f.write("// Generated by openram_gen.py\n")
        if rom_recipes:
            for idx, r in enumerate(rom_recipes):
                addr_w_int = int(math.log2(r.get("num_words", 1))) if r.get("num_words", 1) > 0 else 1
                data_w = r.get("word_size", 32) * 8  # openram word_size is bytes; convert back for wrapper
                macro_name = r.get("name", "behavioral")
                f.write(f"    if ((ADDR_WIDTH == {addr_w_int}) && (DATA_WIDTH == {data_w})) begin : g_macro_{idx}\n")
                f.write(f"        {macro_name} u_rom (\n")
                f.write("        `ifdef USE_POWER_PINS\n")
                f.write("            .vccd1(VPWR), .vssd1(VGND),\n")
                f.write("        `endif\n")
                f.write("            .clk0(clk),\n")
                f.write("            .cs0(en),\n")
                f.write("            .addr0(addr),\n")
                f.write("            .dout0(dout)\n")
                f.write("        );\n")
                f.write("    end")
                if idx < len(rom_recipes) - 1:
                    f.write(" else ")
                else:
                    f.write("\n")
            f.write("    else begin : g_behavioral\n")
            f.write("        rom_1rw_behavioral #(\n")
            f.write("            .ADDR_WIDTH (ADDR_WIDTH),\n")
            f.write("            .DATA_WIDTH (DATA_WIDTH),\n")
            f.write("            .HEXFILE (HEXFILE)\n")
            f.write("        ) u_rom (\n")
            f.write("            .clk  (clk),\n")
            f.write("            .en   (en),\n")
            f.write("            .addr (addr),\n")
            f.write("            .dout (dout),\n")
            f.write("            .VPWR(VPWR),\n")
            f.write("            .VGND(VGND)\n")
            f.write("        );\n")
            f.write("    end\n")
        else:
            f.write("begin : g_behavioral\n")
            f.write("    rom_1rw_behavioral #(\n")
            f.write("        .ADDR_WIDTH (ADDR_WIDTH),\n")
            f.write("        .DATA_WIDTH (DATA_WIDTH),\n")
            f.write("        .HEXFILE (HEXFILE)\n")
            f.write("    ) u_rom (\n")
            f.write("        .clk  (clk),\n")
            f.write("        .en   (en),\n")
            f.write("        .addr (addr),\n")
            f.write("        .dout (dout),\n")
            f.write("        .VPWR(VPWR),\n")
            f.write("        .VGND(VGND)\n")
            f.write("    );\n")
            f.write("end\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--recipes", default="openram_recipes.json")
    parser.add_argument("--out", default=".")
    parser.add_argument("--config", default="config.json")
    parser.add_argument("--force", action="store_true")
    parser.add_argument("--full", action="store_true")
    args = parser.parse_args()

    out_dir = args.out
    recipes_path = args.recipes if os.path.isabs(args.recipes) else os.path.join(os.path.dirname(args.config) or ".", args.recipes)
    if not os.path.isfile(recipes_path):
        print("No recipes file found; nothing to generate.")
        return
    with open(recipes_path) as f:
        recipes = json.load(f)
    if not recipes:
        print("Empty recipes; nothing to generate.")
        return

    macros = collect_macros(recipes, out_dir)
    generate_includes(macros, out_dir, recipes)
    # Update config
    config_path = args.config if os.path.isabs(args.config) else os.path.join(os.path.dirname(args.out) or ".", args.config)
    if os.path.isfile(config_path):
        with open(config_path) as f:
            config = json.load(f)
        if macros:
            config["MACROS"] = macros
        else:
            config.pop("MACROS", None)
        with open(config_path, "w") as f:
            json.dump(config, f, indent=4)
            f.write("\n")
    print(f"OpenRAM generation done. Macros: {list(macros.keys())}")

if __name__ == "__main__":
    main()
